"""Lightweight molecular model used across the engine.

``Molecule3D`` holds an explicit list of atoms with 3D Cartesian coordinates
(angstrom), a total charge and a spin multiplicity. It is deliberately simple so
that the atom editor (add / delete / substitute) and the Gaussian exporter never
need to depend on RDKit's mutable mol objects, which are awkward to edit atom by
atom. Conversions to and from RDKit are provided where a molecular graph is
genuinely required (e.g. force-field optimization).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional

from rdkit import Chem

_PT = Chem.GetPeriodicTable()


def symbol_to_atomic_number(symbol: str) -> int:
    """Return the atomic number for an element symbol, raising on unknowns."""
    try:
        return _PT.GetAtomicNumber(symbol.strip().capitalize())
    except Exception as exc:  # pragma: no cover - RDKit raises RuntimeError
        raise ValueError(f"Unknown element symbol: {symbol!r}") from exc


def atomic_number_to_symbol(z: int) -> str:
    return _PT.GetElementSymbol(int(z))


@dataclass
class Atom:
    """A single atom with a 3D position (angstrom)."""

    symbol: str
    x: float = 0.0
    y: float = 0.0
    z: float = 0.0

    def __post_init__(self) -> None:
        # Normalise the element symbol and validate it eagerly.
        self.symbol = self.symbol.strip().capitalize()
        symbol_to_atomic_number(self.symbol)  # validation
        self.x, self.y, self.z = float(self.x), float(self.y), float(self.z)

    @property
    def atomic_number(self) -> int:
        return symbol_to_atomic_number(self.symbol)


@dataclass
class Molecule3D:
    """An explicit-atom 3D molecule with charge and spin multiplicity."""

    atoms: List[Atom] = field(default_factory=list)
    charge: int = 0
    multiplicity: int = 1
    title: str = "Molecule generated by MolGauss"
    name: str = "molecule"

    # ------------------------------------------------------------------ basics
    def __len__(self) -> int:
        return len(self.atoms)

    @property
    def formula(self) -> str:
        """Hill-system molecular formula for display purposes."""
        counts: dict[str, int] = {}
        for a in self.atoms:
            counts[a.symbol] = counts.get(a.symbol, 0) + 1
        parts: List[str] = []

        def fmt(sym: str) -> str:
            n = counts[sym]
            return sym if n == 1 else f"{sym}{n}"

        if "C" in counts:
            parts.append(fmt("C"))
            if "H" in counts:
                parts.append(fmt("H"))
            for sym in sorted(k for k in counts if k not in ("C", "H")):
                parts.append(fmt(sym))
        else:
            for sym in sorted(counts):
                parts.append(fmt(sym))
        return "".join(parts)

    @property
    def n_electrons(self) -> int:
        """Total electron count (sum of atomic numbers minus total charge)."""
        return sum(a.atomic_number for a in self.atoms) - int(self.charge)

    def suggest_multiplicity(self) -> int:
        """Lowest-spin multiplicity consistent with the electron count.

        Even electrons -> singlet (1), odd electrons -> doublet (2). This is a
        sensible closed-shell default; radicals and high-spin metal complexes
        must still be set by the user.
        """
        return 1 if self.n_electrons % 2 == 0 else 2

    # ------------------------------------------------------------- conversions
    def to_xyz_block(self) -> str:
        """Return a standard multi-line XYZ block (with count + comment header)."""
        lines = [str(len(self.atoms)), self.title]
        for a in self.atoms:
            lines.append(f"{a.symbol:<2} {a.x:>15.8f} {a.y:>15.8f} {a.z:>15.8f}")
        return "\n".join(lines) + "\n"

    def to_rdkit(self) -> Chem.Mol:
        """Build an RDKit mol with a conformer from the current coordinates.

        Bonds are perceived from the 3D geometry via Open Babel so that RDKit
        has connectivity for force-field work. Falls back to a bond-less mol if
        perception fails (still valid for export, just not for MMFF/UFF).
        """
        rw = Chem.RWMol()
        conf = Chem.Conformer(len(self.atoms))
        for i, a in enumerate(self.atoms):
            idx = rw.AddAtom(Chem.Atom(a.atomic_number))
            conf.SetAtomPosition(idx, (a.x, a.y, a.z))
        mol = rw.GetMol()
        mol.AddConformer(conf, assignId=True)
        Chem.SanitizeMol(mol, catchErrors=True)
        return mol

    @classmethod
    def from_rdkit(
        cls,
        mol: Chem.Mol,
        conf_id: int = -1,
        charge: Optional[int] = None,
        multiplicity: Optional[int] = None,
        title: str = "Molecule generated by MolGauss",
        name: str = "molecule",
    ) -> "Molecule3D":
        """Create a Molecule3D from an RDKit mol that already has a conformer."""
        if mol.GetNumConformers() == 0:
            raise ValueError("RDKit mol has no 3D conformer to read coordinates from")
        conf = mol.GetConformer(conf_id)
        atoms: List[Atom] = []
        for i, at in enumerate(mol.GetAtoms()):
            pos = conf.GetAtomPosition(i)
            atoms.append(Atom(at.GetSymbol(), pos.x, pos.y, pos.z))
        total_charge = (
            charge if charge is not None else Chem.GetFormalCharge(mol)
        )
        mult = multiplicity
        obj = cls(
            atoms=atoms,
            charge=int(total_charge),
            multiplicity=1,
            title=title,
            name=name,
        )
        obj.multiplicity = mult if mult is not None else obj.suggest_multiplicity()
        return obj

    def copy(self) -> "Molecule3D":
        return Molecule3D(
            atoms=[Atom(a.symbol, a.x, a.y, a.z) for a in self.atoms],
            charge=self.charge,
            multiplicity=self.multiplicity,
            title=self.title,
            name=self.name,
        )
